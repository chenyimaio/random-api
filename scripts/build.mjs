#!/usr/bin/env node
// scripts/build.mjs
// 把 src/** 和 data/*.json 打成一个自包含的 cloud-functions/[[default]].js。
//
// 为什么要打成单文件：EdgeOne 只在项目根看到 cloud-functions/[[default]].js 时
// 才会把请求交给函数；多文件的相对 import 在构建环境里不保证能解析。
// JSON 数据也被内联进来，所以函数运行时不需要读文件。
//
// 关键约定：**esbuild 缺失时不要失败**。
// 产物本身是提交进仓库的，构建机上装不上 esbuild（新版 npm 默认拦 postinstall，
// 或者 devDependencies 被裁掉）时，继续用仓库里那份即可 —— 让构建挂掉会把整个
// 部署回退到上一次的旧产物，表面上"部署成功"，实际跑的是旧代码，极难排查。

import { existsSync } from 'node:fs';
import { execSync } from 'node:child_process';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..');
const outfile = process.env.OUT || resolve(root, 'cloud-functions/[[default]].js');

// 页面的 /NOTICE.md 指向 public/，这里保证它和仓库根的说明始终同步。
// AGPL §13 要求网络用户能拿到许可与来源说明，所以放在最前面 ——
// 即使 esbuild 缺失、走"沿用已提交产物"的提前退出分支，这份文件也会更新。
try {
  const { readFileSync, writeFileSync } = await import('node:fs');
  writeFileSync(resolve(root, 'public', 'NOTICE.md'), readFileSync(resolve(root, 'NOTICE.md')));
} catch { /* 没有 NOTICE.md 就跳过 */ }

let esbuild = null;
try {
  esbuild = await import('esbuild');
} catch (e) {
  console.warn('[build] esbuild 不可用：', e.message.split('\n')[0]);
}

if (!esbuild) {
  if (existsSync(outfile)) {
    console.warn(`[build] 沿用仓库里已提交的产物：${outfile}`);
    console.warn('[build] 注意：改了 src/** 但没重新打包时，线上仍会跑旧逻辑');
    process.exit(0);
  }
  console.error('[build] 没有 esbuild，仓库里也没有产物，无法继续');
  process.exit(1);
}

// 构建标识：git 短 sha + 打包时间。拿不到 git（平台可能不带 .git）就退回时间戳。
let buildId = `t${new Date().toISOString().replace(/[-:TZ.]/g, '').slice(0, 14)}`;
try {
  const sha = execSync('git rev-parse --short HEAD', { cwd: root, encoding: 'utf8' }).trim();
  if (sha) buildId = sha;
} catch { /* 用时间戳 */ }

await esbuild.build({
  define: { __BUILD_ID__: JSON.stringify(buildId) },
  entryPoints: [resolve(root, 'src/makers.js')],
  outfile,
  bundle: true,
  platform: 'node',
  target: 'node20',
  format: 'esm',
  legalComments: 'none',
  minify: false, // 保留可读性：这个产物是要能被审查的
  banner: {
    js: '// generated by random-api/scripts/build.mjs — 改 src/** 后重新 npm run build',
  },
});

// 打完立刻自检：产物里必须有当前版本的标记，否则说明打包内容不对。
// esbuild 会把单引号统一成双引号，所以按"名字 + 版本号"匹配，不苛求引号形式。
import { readFileSync } from 'node:fs';
const text = readFileSync(outfile, 'utf8');
const pkg = JSON.parse(readFileSync(resolve(root, 'package.json'), 'utf8'));
const marker = new RegExp(`API_VERSION\\s*=\\s*["']${pkg.version.replace(/\./g, '\\.')}["']`);
if (!marker.test(text)) {
  console.error(`[build] 产物里找不到版本标记 v${pkg.version}，打包内容可疑，中止`);
  process.exit(1);
}
if (!text.includes(buildId)) {
  console.error(`[build] 产物里没有注入 BUILD_ID（${buildId}），define 没生效`);
  process.exit(1);
}

// 数据新鲜度自检：产物必须包含当前全量句子，否则同步了新数据却仍部署旧产物。
// 用最后一条的 uuid 做指纹 —— 它是纯 ASCII，不会被 esbuild 转义成 \uXXXX；
// 用中文正文去搜会误报（esbuild 会把非 ASCII 转成转义序列）。
try {
  const remote = JSON.parse(readFileSync(resolve(root, 'data', 'quotes.remote.json'), 'utf8'));
  const probe = [...remote].reverse().find((q) => typeof q.uuid === 'string' && /^[\x20-\x7e]+$/.test(q.uuid));
  if (probe && !text.includes(probe.uuid)) {
    console.error('[build] 产物里找不到最新句子数据，说明数据没被内联进去，中止');
    process.exit(1);
  }
  console.log(`[build] 数据自检通过：${remote.length} 条句子已内联`);
} catch (e) {
  // 没有 remote 数据文件（比如精简部署）就跳过这项检查
}

console.log(`[build] wrote ${outfile} (v${pkg.version} @ ${buildId}, ${(text.length / 1024).toFixed(0)} KB)`);
